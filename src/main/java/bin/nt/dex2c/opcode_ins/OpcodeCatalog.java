    private OpcodeCatalog() {
    }

    /** One opcode of the legacy inventory. */
    public static final class Entry {
        private final int value;
        private final String opcode;
        private final String originalHandler;

        /**
         * @param value           the opcode value
         * @param opcode          the opcode name, e.g. {@code const/4}
         * @param originalHandler the original handler function name
         */
        public Entry(int value, String opcode, String originalHandler) {
            this.value = value;
            this.opcode = opcode;
            this.originalHandler = originalHandler;
        }

        /** The opcode value. */
        public int value() {
            return value;
        }

        /** The opcode name, e.g. {@code const/4}. */
        public String opcode() {
            return opcode;
        }

        /** The original handler function name. */
        public String originalHandler() {
            return originalHandler;
        }
    }
